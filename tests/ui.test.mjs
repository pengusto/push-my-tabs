import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const template = await readFile("src/app.html", "utf8");
const styles = await readFile("src/styles.css", "utf8");
const navigation = [...template.matchAll(/data-view="([^"]+)"/g)].map((m) => m[1]);
const pages = [...template.matchAll(/data-page="([^"]+)"/g)].map((m) => m[1]);
assert.deepEqual(navigation, ["navigation", "tabloop", "layout", "shortcuts", "settings"]);
assert.deepEqual(pages, navigation, "every navigation destination has exactly one view");
const ids = [...template.matchAll(/\bid="([^"]+)"/g)].map((m) => m[1]);
assert.equal(new Set(ids).size, ids.length, "template IDs must be unique");
assert.match(template, /role="status" aria-live="polite"/);
assert.match(template, /role="switch"/);
assert.doesNotMatch(template, /CLUT|on(?:click|change)=|<script/);
assert.match(styles, /:focus-visible/);
assert.match(styles, /prefers-reduced-motion/);
assert.match(styles, /\[hidden\].*display: none !important/);
assert.doesNotMatch(styles, /box-shadow:.*\d+px 0/);
console.log("Five-view navigation, template, and accessibility contracts passed");
